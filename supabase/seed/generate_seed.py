def assessment_dates(key: str, bench: str, level: str):
    """Pick a believable assessment date and expiry for one matrix cell."""
    started = STAFF_BY_KEY[key][6]

    if level == "trainee":
        # Training started somewhere in the last few months, no expiry yet.
        assessed = TODAY - timedelta(days=RNG.randint(20, 200))
        if assessed < started:
            assessed = started + timedelta(days=14)
        return assessed, None

    earliest = max(started + timedelta(days=60), TODAY - timedelta(days=912))
    latest = TODAY - timedelta(days=60)
    if earliest > latest:
        earliest = latest - timedelta(days=30)
    span = (latest - earliest).days
    assessed = earliest + timedelta(days=RNG.randint(0, max(span, 1)))

    override = EXPIRY_OVERRIDES.get((key, bench))
    expires = override if override else assessed + timedelta(days=1095)
    return assessed, expires


def emit_competencies() -> str:
    out = header(
        "030 competency matrix",
        "Who is signed off on what, at what level, and when it expires. The "
        "per-document evidence trail is derived from this.",
    )
    out += "begin;\n\n"

    out += "-- Bench-level competency (what the matrix screen edits) ---------------\n"
    out += ("with data(staff_code, bench_name, level, assessed_on, expires_on, "
            "assessor_code) as (\n  values\n")
    rows = []
    trainee_cells = []
    for bench_name, holders in COMPETENCY.items():
        for key, level in holders.items():
            code = STAFF_BY_KEY[key][1]
            assessed, expires = assessment_dates(key, bench_name, level)
            if level == "trainee":
                assessor = None
                trainee_cells.append((key, bench_name, assessed))
            else:
                pool = [t for t in TRAINERS_FOR_SIGNOFF if t != key]
                assessor = STAFF_BY_KEY[RNG.choice(pool)][1]
            rows.append(
                f"    ({sql_str(code)}, {sql_str(bench_name)}, {sql_str(level)}, "
                f"{sql_str(assessed)}, {sql_str(expires)}, {sql_str(assessor)})"
            )
    out += ",\n".join(rows) + "\n)\n"
    out += textwrap.dedent("""\
        insert into competency (staff_id, bench_id, level, assessed_on, expires_on,
                                assessor_id, document_ref)
        select
          s.id,
          b.id,
          d.level::competency_level,
          d.assessed_on::date,
          d.expires_on::date,
          a.id,
          (select cd.doc_number
             from competency_document cd
            where cd.bench_id = b.id
            order by cd.sort_order
            limit 1)
        from data d
        join staff s on s.staff_code = d.staff_code
        join bench b on b.name = d.bench_name
        left join staff a on a.staff_code = d.assessor_code;

        """)

    out += "-- Evidence trail: signed-off staff hold every document for the bench --\n"
    out += textwrap.dedent("""\
        insert into staff_document (staff_id, document_id, status, assessed_on, expires_on)
        select c.staff_id, cd.id, 'signed_off', c.assessed_on, c.expires_on
        from competency c
        join competency_document cd on cd.bench_id = c.bench_id
        where c.level in ('competent', 'trainer')
        on conflict (staff_id, document_id) do nothing;

        """)

    out += "-- Trainees are partway through, document by document ------------------\n"
    out += "with data(staff_code, bench_name, doc_number, status, assessed_on) as (\n  values\n"
    rows = []
    for key, bench_name, assessed in trainee_cells:
        code = STAFF_BY_KEY[key][1]
        docs = next(d for b, _g, _mn, _mx, _l, _r, d in BENCHES if b == bench_name)
        # Roughly the first half signed off, the rest live or not yet started.
        done = RNG.randint(0, max(len(docs) - 1, 0))
        for i, doc in enumerate(docs):
            if i < done:
                status = "signed_off"
                when = assessed + timedelta(days=i * 9)
            elif i == done:
                status = "in_training"
                when = None
            else:
                status = "not_started"
                when = None
            rows.append(
                f"    ({sql_str(code)}, {sql_str(bench_name)}, {sql_str(str(doc))}, "
                f"{sql_str(status)}, {sql_str(when)})"
            )
    out += ",\n".join(rows) + "\n)\n"
    out += textwrap.dedent("""\
        insert into staff_document (staff_id, document_id, status, assessed_on)
        select s.id, cd.id, d.status::doc_status, d.assessed_on::date
        from data d
        join staff s on s.staff_code = d.staff_code
        join bench b on b.name = d.bench_name
        join competency_document cd on cd.bench_id = b.id and cd.doc_number = d.doc_number
        on conflict (staff_id, document_id) do nothing;

        """)
    out += "commit;\n"
    return out


