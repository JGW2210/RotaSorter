def sql_str(v) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, date):
        return f"'{v.isoformat()}'"
    return "'" + str(v).replace("'", "''") + "'"


def header(title: str, note: str = "") -> str:
    bar = "-- " + "=" * 69
    out = f"{bar}\n-- RotaSorter seed — {title}\n"
    if note:
        out += textwrap.indent(textwrap.fill(note, 68), "-- ") + "\n"
    out += "-- Synthetic data only. Generated by supabase/seed/generate_seed.py\n"
    out += f"{bar}\n\n"
    return out


