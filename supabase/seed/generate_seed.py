def main() -> None:
    files = {
        "0010_reference_data.sql": emit_reference(),
        "0020_staff.sql": emit_staff(),
        "0030_competencies.sql": emit_competencies(),
        "0040_rules_settings.sql": emit_rules(),
    }
    for name, body in files.items():
        (OUT / name).write_text(body)
        print(f"wrote {name} ({len(body.splitlines())} lines)")

    # A quick arithmetic sanity check on the week, printed so a change to the
    # roster or the bench list shows up as a warning rather than a failed solve.
    print("\nweekday headroom for the seeded week:")
    for offset, label in enumerate(["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]):
        day = SEED_WEEK + timedelta(days=offset)
        iso = offset + 1
        available = 0
        for key, _c, _n, _g, _f, days, _s in STAFF:
            if iso not in days:
                continue
            if any(k == key and s <= day <= e for k, s, e, _kind, _note in ABSENCES):
                continue
            available += 1
        needed = sum(
            mn
            for _n, _g, _dmn, _dmx, _l, reqs, _d in BENCHES
            for _label, days, mn, _mx in reqs
            if iso in days
        )
        # A trainee placed on a bench that needs one person consumes two: the
        # trainee and the colleague supervising them. Two spare is the floor
        # that keeps three trainees placeable.
        flag = "  <-- TIGHT" if available - needed < 2 else ""
        print(f"  {label}: {needed} needed, {available} available, "
              f"headroom {available - needed}{flag}")


if __name__ == "__main__":
    main()
